#!/usr/bin/env node
// Fetch real hourly PV output (PVGIS-ERA5 seriescalc, 2014–2023) for the sites the weather stress
// test replays, with each site's frozen PVcalc mounting (tilt, azimuth, 14% loss), and write
// data/weather-hourly.js: W per kWp for every hour in local solar time, base64 Uint16. Node only.
//
//   node scripts/build-weather.mjs            # fetch and write
//   node scripts/build-weather.mjs --check    # exit 1 if the file is missing a site or year
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'data', 'weather-hourly.js');
const START_YEAR = 2014;
const END_YEAR = 2023;
// Best sites in the abundance scoreboard, sites the company fills, and a cloudier contrast.
const SITES = {
  'namibia-walvis-bay': 'pvgis-walvis-bay.json',
  'morocco-dakhla': 'pvgis-dakhla.json',
  'levant-dead-sea': 'pvgis-dead-sea.json',
  'israel-ashkelon': 'pvgis-ashkelon.json',
  'chile-mejillones': 'pvgis-mejillones.json',
  'au-port-hedland': 'pvgis-port-hedland.json',
  'saudi-oxagon': 'pvgis-oxagon.json',
  'spain-almeria': 'pvgis-almeria.json',
  'chile-taltal': 'pvgis-taltal.json',
  'namibia-luderitz': 'pvgis-luderitz.json',
  'mauritania-nouadhibou': 'pvgis-nouadhibou.json',
  'chile-iquique': 'pvgis-iquique.json',
};
const API = 'https://re.jrc.ec.europa.eu/api/v5_3/seriescalc';

async function fetchSite(id, file) {
  const frozen = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', file), 'utf8'));
  const { latitude, longitude } = frozen.inputs.location;
  const fixed = frozen.inputs.mounting_system.fixed;
  const q = new URLSearchParams({
    lat: latitude, lon: longitude, raddatabase: 'PVGIS-ERA5', startyear: START_YEAR, endyear: END_YEAR,
    pvcalculation: 1, peakpower: 1, loss: frozen.inputs.pv_module.system_loss,
    angle: fixed.slope.value, aspect: fixed.azimuth.value, outputformat: 'json',
  });
  const res = await fetch(`${API}?${q}`);
  if (!res.ok) throw new Error(`${id}: PVGIS ${res.status}`);
  const rows = (await res.json()).outputs.hourly;
  // PVGIS times are UTC; shift by the longitude to local solar time so days split at night.
  const shift = Math.round(longitude / 15);
  const n = rows.length;
  const w = new Uint16Array(n);
  for (let i = 0; i < n; i += 1) w[(i + shift + n) % n] = Math.max(0, Math.min(65535, Math.round(rows[i].P)));
  const meanKWhPerDay = w.reduce((a, b) => a + b, 0) / 1000 / (n / 24);
  return {
    latitude, longitude, hours: n, utcShiftHours: shift, meanKWhPerKWpDay: Number(meanKWhPerDay.toFixed(3)),
    data: Buffer.from(w.buffer).toString('base64'),
  };
}

const check = process.argv.includes('--check');
if (check) {
  if (!fs.existsSync(OUT)) { console.error('data/weather-hourly.js missing'); process.exit(1); }
  const { WEATHER } = (await import(OUT)).default;
  const missing = Object.keys(SITES).filter(id => !WEATHER.sites[id]);
  if (missing.length) { console.error('missing sites:', missing.join(', ')); process.exit(1); }
  console.log('data/weather-hourly.js has every site');
  process.exit(0);
}
const out = { source: `PVGIS-ERA5 seriescalc ${START_YEAR}–${END_YEAR}, each site's frozen PVcalc mounting`, startYear: START_YEAR, endYear: END_YEAR, sites: {} };
for (const [id, file] of Object.entries(SITES)) {
  out.sites[id] = await fetchSite(id, file);
  console.log(id, out.sites[id].hours, 'h, mean', out.sites[id].meanKWhPerKWpDay, 'kWh/kWp·day');
}
fs.writeFileSync(OUT, `// Generated by scripts/build-weather.mjs — do not edit. Hourly PV output, W per kWp, local solar time,
// base64 little-endian Uint16 per site. Node only (the weather stress test); the app does not load it.
(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.FoundryWeather = data;
})(globalThis, { WEATHER: ${JSON.stringify(out)} });
`);
console.log('wrote', path.relative(ROOT, OUT), (fs.statSync(OUT).size / 1e6).toFixed(2), 'MB');
